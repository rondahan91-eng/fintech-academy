# זמין לבדיקות: ‏OUTPUT · LINES · VARS (המשתנים שהתלמיד יצר)


def _accounts():
    """כל החשבונות שהתלמיד יצר. מזוהים לפי הממשק, לא לפי שם המשתנה."""
    return [v for v in VARS.values()
            if hasattr(v, "statement") and not isinstance(v, type)]


def _owned_by(name):
    for acc in _accounts():
        if name in str(acc.owner()):
            return acc
    return None


